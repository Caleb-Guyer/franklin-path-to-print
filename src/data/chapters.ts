function ids(spec: string) {
  return spec.split(',').flatMap((x) => {
    const [a, b] = x.split('-').map(Number);
    return Array.from({ length: (b ?? a) - a + 1 }, (_, i) => `f${String(a + i).padStart(3, '0')}`);
  });
}
function scene(
  id: string,
  chapter: number,
  title: string,
  era: string,
  location: string,
  narration: string,
  spec: string,
  extra: Partial<Event> = {},
): Event {
  const factIds = ids(spec);
  return {
    id,
    chapter,
    title,
    era,
    location,
    narration,
    factIds,
    sourcePages: [...new Set(factIds.flatMap((id) => factById[id].sourcePages))].sort(
      (a, b) => a - b,
    ),
    order: Number(id.slice(1)),
    ...extra,
  };
}
